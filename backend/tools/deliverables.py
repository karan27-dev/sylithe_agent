def write_pptx(spec: dict, sources: list[dict] | None = None) -> Deliverable:
    """
    spec = {
      "title": str, "subtitle": str,
      "slides": [ {"title": str, "bullets": [str], "notes": str} ]
    }
    """
    from pptx import Presentation
    from pptx.util import Pt

    title = spec.get("title") or "Presentation"
    pr = Presentation()

    s = pr.slides.add_slide(pr.slide_layouts[0])
    s.shapes.title.text = title
    if len(s.placeholders) > 1:
        s.placeholders[1].text = spec.get("subtitle") or ""

    for sl in spec.get("slides") or []:
        slide = pr.slides.add_slide(pr.slide_layouts[1])
        slide.shapes.title.text = str(sl.get("title") or "")
        bullets = [str(b) for b in (sl.get("bullets") or [])]
        if bullets:
            tf = slide.placeholders[1].text_frame
            tf.text = bullets[0]
            for b in bullets[1:]:
                para = tf.add_paragraph()
                para.text = b
                para.level = 0
        if sl.get("notes"):
            slide.notes_slide.notes_text_frame.text = str(sl["notes"])

    srcs = _sources_block(sources)
    if srcs:
        slide = pr.slides.add_slide(pr.slide_layouts[1])
        slide.shapes.title.text = "Sources"
        tf = slide.placeholders[1].text_frame
        tf.text = srcs[0]
        for s_ in srcs[1:]:
            para = tf.add_paragraph()
            para.text = s_
            para.level = 0

    path = _stamp(title, "pptx")
    pr.save(path)
    return Deliverable(path, "pptx", title, path.stat().st_size)


