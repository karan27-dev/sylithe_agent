def write_docx(spec: dict, sources: list[dict] | None = None) -> Deliverable:
    """
    spec = {
      "title": str,
      "subtitle": str | None,
      "meta": {label: value},            # Ref no, date, unit ...
      "sections": [ {"heading": str,
                     "paragraphs": [str],
                     "bullets": [str],
                     "table": {"columns": [...], "rows": [[...]]}} ],
      "decision": str | None,            # highlighted box at the end
      "signoff": [str],
    }
    """
    from docx import Document
    from docx.shared import Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    title = spec.get("title") or "Document"
    d = Document()

    d.add_heading(title, 0)
    if spec.get("subtitle"):
        p = d.add_paragraph(spec["subtitle"])
        p.runs[0].italic = True

    meta = spec.get("meta") or {}
    if meta:
        line = "    ".join(f"{k}: {v}" for k, v in meta.items())
        mp = d.add_paragraph(line)
        mp.runs[0].font.size = Pt(9)
        mp.runs[0].font.color.rgb = RGBColor(0x60, 0x60, 0x60)

    for sec in spec.get("sections") or []:
        if sec.get("heading"):
            d.add_heading(str(sec["heading"]), 1)
        for para in sec.get("paragraphs") or []:
            d.add_paragraph(str(para))
        for b in sec.get("bullets") or []:
            d.add_paragraph(str(b), style="List Bullet")
        tbl = sec.get("table")
        if tbl and tbl.get("columns"):
            cols = [str(c) for c in tbl["columns"]]
            t = d.add_table(rows=1, cols=len(cols))
            t.style = "Table Grid"
            for i, c in enumerate(cols):
                cell = t.rows[0].cells[i]
                cell.text = c
                for r in cell.paragraphs[0].runs:
                    r.bold = True
            for row in tbl.get("rows") or []:
                cells = t.add_row().cells
                for i, v in enumerate(row[:len(cols)]):
                    cells[i].text = "" if v is None else str(v)

    if spec.get("decision"):
        d.add_heading("Decision", 1)
        dp = d.add_paragraph(str(spec["decision"]))
        dp.runs[0].bold = True

    for line in spec.get("signoff") or []:
        d.add_paragraph(str(line))

    srcs = _sources_block(sources)
    if srcs:
        d.add_page_break()
        d.add_heading("Sources", 1)
        note = d.add_paragraph(CITE_NOTE)
        note.runs[0].font.size = Pt(9)
        note.runs[0].italic = True
        for s in srcs:
            sp = d.add_paragraph(s, style="List Number")
            sp.runs[0].font.size = Pt(9)

    path = _stamp(title, "docx")
    d.save(path)
    return Deliverable(path, "docx", title, path.stat().st_size)


