def write_xlsx(spec: dict, sources: list[dict] | None = None) -> Deliverable:
    """
    spec = {
      "title": str,
      "sheets": [ {"name": str,
                   "columns": [...], "rows": [[...]],
                   "formulas": [{"cell": "E2", "formula": "=D2/C2"}],
                   "notes": [str]} ]
    }

    Formulas are written as real Excel formulas, not pre-computed values, so
    "calculations with steps shown" survives in the file the engineer opens.
    """
    from openpyxl import Workbook
    from openpyxl.styles import Font, Alignment, PatternFill

    title = spec.get("title") or "Workbook"
    wb = Workbook()
    wb.remove(wb.active)
    head_fill = PatternFill("solid", fgColor="EEEAE0")

    for sheet in spec.get("sheets") or [{"name": "Sheet1"}]:
        ws = wb.create_sheet(str(sheet.get("name") or "Sheet")[:31])
        cols = [str(c) for c in (sheet.get("columns") or [])]
        if cols:
            ws.append(cols)
            for c in ws[1]:
                c.font = Font(bold=True)
                c.fill = head_fill
                c.alignment = Alignment(horizontal="center")
        for row in sheet.get("rows") or []:
            ws.append(list(row))
        for f in sheet.get("formulas") or []:
            if f.get("cell") and f.get("formula"):
                ws[f["cell"]] = f["formula"]
        if cols:
            for i, c in enumerate(cols, 1):
                width = max(len(c) + 2, 12)
                ws.column_dimensions[ws.cell(1, i).column_letter].width = width
        notes = sheet.get("notes") or []
        if notes:
            ws.append([])
            for n in notes:
                ws.append([str(n)])

    if sources:
        ws = wb.create_sheet("Sources")
        ws.append(["Ref", "Source"])
        for c in ws[1]:
            c.font = Font(bold=True)
        for s in sources:
            ws.append([f"[{s.get('n','?')}]", s.get("cite") or s.get("source", "")])
        ws.column_dimensions["B"].width = 70

    path = _stamp(title, "xlsx")
    wb.save(path)
    return Deliverable(path, "xlsx", title, path.stat().st_size)


