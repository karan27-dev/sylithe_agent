# A spec is only usable if it carries the payload key for its kind. Without
# this check a parser can lock onto a NESTED object (a "meta" block, say) and
# report success while the document comes out empty.
TOP_KEYS = {
    "docx": ("sections", "title", "decision"),
    "xlsx": ("sheets", "title"),
    "pptx": ("slides", "title"),
}
PAYLOAD_KEY = {"docx": "sections", "xlsx": "sheets", "pptx": "slides"}


def _try_json(raw: str) -> dict | None:
    for attempt in (raw, re.sub(r",(\s*[}\]])", r"\1", raw)):
        try:
            val = json.loads(attempt)
            return val if isinstance(val, dict) else None
        except json.JSONDecodeError:
            continue
    return None


def _candidates(text: str):
    """Every plausible JSON payload in a model reply, best first."""
    t = text.strip()
    # 1. the whole thing
    yield t
    # 2. a fenced block
    for m in re.finditer(r"```(?:json)?\s*(.*?)\s*```", t, re.S):
        yield m.group(1)
    # 3. balanced braces from each opening brace
    for start in (i for i, ch in enumerate(t) if ch == "{"):
        depth = 0
        for i, ch in enumerate(t[start:], start):
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    yield t[start:i + 1]
                    break
    # 4. the model dropped the outer braces and began with a quoted key
    if re.match(r'^"[A-Za-z_]', t):
        yield "{" + t.rstrip().rstrip(",") + "}"
        yield "{" + t.rstrip().rstrip(",") + "}}"      # one unclosed nesting


def parse_spec(text: str, kind: str | None = None) -> dict | None:
    """
    Pull a usable document spec out of a model reply.

    Small models wrap JSON in prose or fences, emit trailing commas, and
    sometimes omit the outer braces entirely. Be liberal about the input but
    strict about the result: when `kind` is given, the object must contain a
    key that actually carries content for that kind, otherwise we would
    silently render an empty document.
    """
    if not text:
        return None
    wanted = TOP_KEYS.get(kind or "", ())
    fallback = None

    for raw in _candidates(text):
        val = _try_json(raw)
        if val is None:
            continue
        if not wanted:
            return val
        if PAYLOAD_KEY.get(kind) in val:        # has the real payload
            return val
        if any(w in val for w in wanted) and fallback is None:
            fallback = val                      # title-only: keep looking
    return fallback


WRITERS = {"docx": write_docx, "xlsx": write_xlsx, "pptx": write_pptx}


def build(kind: str, spec: dict, sources: list[dict] | None = None) -> Deliverable:
    if kind not in WRITERS:
        raise ValueError(f"unknown deliverable kind {kind!r}; have {sorted(WRITERS)}")
    return WRITERS[kind](spec, sources)


