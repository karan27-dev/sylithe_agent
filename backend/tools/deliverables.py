"""
Deliverable writers - turn an answer into a real file.

PS 26117, Expected Solution (verbatim):
  "Output should be real deliverables, approval notes, PPT/Word/Excel files,
   working code, calculations with steps shown, not just chat replies."
  "...for example reading a scanned inspection report, pulling out key
   findings and drafting an approval note as a Word file."

So this module is the difference between a chatbot and the thing the PS asks
for. Everything is written locally with python-docx / openpyxl / python-pptx;
no template service, no cloud renderer.

Design note: the model does NOT write the file. The model returns structured
JSON, and Python renders it. A 2b model cannot be trusted to produce valid
OOXML, but it can fill a schema. That split also means a malformed model
response degrades into a partly-empty document instead of a crash.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = _ROOT / "data" / "deliverables"

# Documents carry a citation line so a reader can trace any claim back to the
# source file and page. Without this an "approval note" is just generated text.
CITE_NOTE = ("Generated by Sovereign Workbench from the indexed corpus. "
             "Every finding is traceable to the source listed below.")


@dataclass
class Deliverable:
    path: Path
    kind: str
    title: str
    bytes: int

    def as_dict(self) -> dict:
        return {"file": self.path.name, "path": str(self.path),
                "kind": self.kind, "title": self.title, "bytes": self.bytes}


def _stamp(name: str, ext: str) -> Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    safe = re.sub(r"[^A-Za-z0-9_.-]+", "_", name).strip("_")[:60] or "document"
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    return OUT_DIR / f"{safe}_{ts}.{ext}"


def _sources_block(sources: list[dict] | None) -> list[str]:
    if not sources:
        return []
    out = []
    for s in sources:
        n = s.get("n", "?")
        cite = s.get("cite") or s.get("source", "")
        out.append(f"[{n}] {cite}")
    return out


