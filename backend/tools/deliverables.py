def list_deliverables() -> list[dict]:
    if not OUT_DIR.exists():
        return []
    out = []
    for f in sorted(OUT_DIR.iterdir(), key=lambda x: x.stat().st_mtime, reverse=True):
        if f.is_file() and f.suffix.lstrip(".") in WRITERS:
            out.append({"file": f.name, "kind": f.suffix.lstrip("."),
                        "bytes": f.stat().st_size, "mtime": f.stat().st_mtime})
    return out
