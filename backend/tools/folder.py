def places() -> list[dict]:
    """Obvious starting points, so nobody has to type a path from memory."""
    home = Path.home()
    out = []
    for label, path in [("Home", home), ("Desktop", home / "Desktop"),
                        ("Documents", home / "Documents"),
                        ("Downloads", home / "Downloads")]:
        if path.exists():
            out.append({"label": label, "path": str(path)})
    return out


def listdir(folder: str | Path) -> dict:
    """
    One level of a directory, for the picker.

    A browser file picker cannot hand back a real filesystem path - that is a
    deliberate security boundary, and it is why typing the path was the only
    option at first. But this backend runs on the same machine, so it can list
    directories directly and the picker gets real paths without uploading or
    copying anything.
    """
    root = Path(folder).expanduser()
    if not root.exists():
        return {"error": f"No such folder: {root}"}
    if not root.is_dir():
        return {"error": f"Not a folder: {root}"}

    dirs, n_supported, n_files = [], 0, 0
    try:
        for p in sorted(root.iterdir(), key=lambda x: x.name.lower()):
            if p.name.startswith("."):
                continue
            if p.is_dir():
                if p.name in SKIP_DIRS:
                    continue
                # how many readable documents sit directly inside, so the user
                # can see which branch is worth opening
                try:
                    inside = sum(1 for c in p.iterdir()
                                 if c.is_file()
                                 and c.suffix.lower() in pipeline.SUPPORTED)
                except PermissionError:
                    inside = -1
                dirs.append({"name": p.name, "path": str(p), "docs": inside})
            elif p.is_file():
                n_files += 1
                if p.suffix.lower() in pipeline.SUPPORTED:
                    n_supported += 1
    except PermissionError:
        return {"error": f"No permission to read {root}"}

    parent = str(root.parent) if root.parent != root else None
    return {"path": str(root), "parent": parent, "dirs": dirs[:200],
            "files": n_files, "supported": n_supported,
            "crumbs": [{"name": q.name or "/", "path": str(q)}
                       for q in reversed([root, *root.parents])][-6:]}



def choose() -> dict:
    """
    Open the machine's own folder chooser.

    A browser cannot open a dialog that returns a filesystem path - that is the
    security boundary that forced typing (and the in-page browser) in the
    first place. This backend is a local process though, so it can ask the OS
    directly and hand back a real path - one native dialog per platform, in
    the toolkit that ships with that OS rather than one this project would
    have to bundle.
    """
    import sys

    if sys.platform == "darwin":
        return _choose_macos()
    if sys.platform == "win32":
        return _choose_windows()
    return _choose_linux()


def _choose_macos() -> dict:
    import subprocess
    script = ('POSIX path of (choose folder with prompt '
              '"Choose a folder for the Sovereign Workbench to read")')
    try:
        r = subprocess.run(["osascript", "-e", script],
                           capture_output=True, text=True, timeout=180)
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return {"error": "The chooser timed out."}
    if r.returncode != 0:
        err = r.stderr or ""
        # Cancelling is the ordinary path, not an error. macOS reports it as
        # "User cancelled. (-128)" - with two l's. This code looked for the
        # American spelling, never matched, and fell into the error branch, so
        # pressing Cancel opened the fallback path box instead of doing
        # nothing. Match the error NUMBER, which does not vary by locale or
        # spelling, and keep both spellings as a belt.
        if "-128" in err or "cancel" in err.lower():
            return {"cancelled": True}
        return {"error": err.strip()[:160] or "Could not open the chooser"}
    return {"path": r.stdout.strip().rstrip("/")}


def _choose_windows() -> dict:
    # WinForms' FolderBrowserDialog, driven from PowerShell so nothing needs
    # bundling - every Windows box already has both. It needs an STA thread;
    # classic powershell.exe (not pwsh/PowerShell 7) is STA by default, which
    # is the whole reason this targets "powershell" specifically.
    import subprocess
    script = (
        "Add-Type -AssemblyName System.Windows.Forms | Out-Null;"
        "$f = New-Object System.Windows.Forms.FolderBrowserDialog;"
        "$f.Description = 'Choose a folder for the Sovereign Workbench to read';"
        "$f.ShowNewFolderButton = $false;"
        "if ($f.ShowDialog() -eq [System.Windows.Forms.DialogResult]::OK) {"
        "  Write-Output $f.SelectedPath"
        "}"
    )
    try:
        r = subprocess.run(
            ["powershell", "-NoProfile", "-NonInteractive", "-Command", script],
            capture_output=True, text=True, timeout=180)
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return {"error": "Native chooser is unavailable - browse instead."}
    if r.returncode != 0:
        return {"error": (r.stderr or "").strip()[:160]
                or "Could not open the chooser"}
    path = r.stdout.strip()
    # No SelectedPath printed means Cancel, not an error - ShowDialog()
    # returned anything other than OK.
    return {"path": path} if path else {"cancelled": True}


def _choose_linux() -> dict:
    # No single toolkit ships with every distro. Try the two that cover
    # GNOME and KDE; if neither binary exists, fall back honestly instead of
    # guessing at a third.
    import shutil
    import subprocess

    for binary, args in (
        ("zenity", ["--file-selection", "--directory",
                    "--title=Choose a folder for the Sovereign Workbench to read"]),
        ("kdialog", ["--getexistingdirectory", str(Path.home())]),
    ):
        if not shutil.which(binary):
            continue
        try:
            r = subprocess.run([binary, *args], capture_output=True,
                               text=True, timeout=180)
        except subprocess.TimeoutExpired:
            return {"error": "The chooser timed out."}
        if r.returncode != 0:
            return {"cancelled": True}      # both tools exit non-zero on Cancel
        path = r.stdout.strip()
        return {"path": path} if path else {"cancelled": True}
    return {"error": "No folder chooser found (zenity/kdialog) - browse instead."}
