"""
Point the workbench at a folder on this machine and index what is in it.

PS 26117 asks for "a local knowledge base connector" so the assistant can
ground itself in "the organization's own manuals, SOPs and past
correspondence". Uploading files one at a time does not describe how an
engineer actually works - the manuals already sit in a folder on the server.

Nothing leaves the machine: this reads from a local path with the same ingest
pipeline the upload button uses.

Two rules that matter more than they look:

  * The folder is walked, never copied. A 400 MB manuals directory should not
    be duplicated into data/corpus to be read once.
  * Files generated by this system are skipped, as everywhere else. A folder
    that happens to contain last week's approval notes must not turn them into
    evidence.
"""

from __future__ import annotations

import os
import time
from dataclasses import dataclass, field
from pathlib import Path

from ingest import pipeline

# Walking an entire home directory by accident should not be possible - but
# 400 turned out to be a wall a perfectly ordinary "Documents" folder hits
# (1,964 supported files on one real laptop), not just an accident guard.
# Raised to a size that covers a real folder of plant manuals; SCAN_CAP above
# is still what stops someone pointing this at their whole home directory.
MAX_FILES = 3000
MAX_BYTES = 2 * 1024 * 1024 * 1024
# A hard ceiling on how many filesystem entries one scan will even look at,
# independent of MAX_FILES - see the cycle note on preview() below for why
# this needs to be a wall during the walk, not a check after it finishes.
SCAN_CAP = 20_000
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv",
             "Library", "System", ".Trash", "site-packages", ".cache",
             # Windows noise, and the two that matter most: "Application
             # Data" and "Local Settings" are legacy reparse points that
             # exist purely to redirect old software into AppData - walking
             # into one revisits AppData a second time under a different
             # name, and on some profiles they form an outright cycle back
             # on themselves.
             "AppData", "Application Data", "Local Settings",
             "$RECYCLE.BIN", "System Volume Information"}


@dataclass
class Scan:
    root: str
    found: int = 0
    supported: int = 0
    indexed: int = 0
    chunks: int = 0
    skipped_self: int = 0
    failed: int = 0
    seconds: float = 0.0
    by_type: dict = field(default_factory=dict)
    files: list = field(default_factory=list)
    error: str | None = None

    def as_dict(self) -> dict:
        return {k: getattr(self, k) for k in
                ("root", "found", "supported", "indexed", "chunks",
                 "skipped_self", "failed", "seconds", "by_type", "files",
                 "error")}


def preview(folder: str | Path) -> Scan:
    """What is in there, without reading a single document.

    Walks with os.walk rather than Path.rglob, and for one reason: rglob
    follows a directory-shaped reparse point wherever it points, and never
    checks whether it has been there before. A Windows profile is full of
    exactly that - "Application Data" and "Local Settings" are legacy
    junctions back into AppData, and on some profiles they form an actual
    cycle. rglob("*") on one of those does not error and does not finish; it
    was reported back as the folder picker "timing out", because from the
    browser's side that is indistinguishable from a request that never
    returns. Tracking each directory's resolved real path and refusing to
    descend into one twice closes that hole regardless of which specific
    reparse point causes it, and a hard cap on entries visited is the
    backstop for a folder that is merely enormous rather than cyclic.
    """
    root = Path(folder).expanduser()
    s = Scan(root=str(root))
    if not root.exists():
        s.error = f"No such folder: {root}"
        return s
    if not root.is_dir():
        s.error = f"Not a folder: {root}"
        return s

    total_bytes = 0
    visited_dirs: set[str] = set()
    scanned = 0
    for dirpath, dirnames, filenames in os.walk(root, topdown=True, followlinks=False):
        try:
            real = os.path.realpath(dirpath)
        except OSError:
            real = dirpath
        if real in visited_dirs:
            dirnames[:] = []
            continue
        visited_dirs.add(real)

        dirnames[:] = sorted(d for d in dirnames
                             if d not in SKIP_DIRS and not d.startswith("."))
        for fname in sorted(filenames):
            if fname.startswith("."):
                continue
            scanned += 1
            if scanned > SCAN_CAP:
                s.error = (f"More than {SCAN_CAP:,} files under this folder - "
                           "point at a narrower one.")
                return s
            p = Path(dirpath) / fname
            try:
                if not p.is_file():
                    continue
            except OSError:
                continue
            s.found += 1
            ext = p.suffix.lower()
            if ext in pipeline.SUPPORTED:
                s.supported += 1
                s.by_type[ext] = s.by_type.get(ext, 0) + 1
                try:
                    total_bytes += p.stat().st_size
                except OSError:
                    continue
                if len(s.files) < MAX_FILES:
                    s.files.append(str(p))
        if s.supported > MAX_FILES:
            s.error = (f"{s.supported} supported files - over the {MAX_FILES} limit. "
                       "Point at a narrower folder.")
            return s
        if total_bytes > MAX_BYTES:
            s.error = (f"{total_bytes/1048576:.0f} MB of documents - over the "
                       f"{MAX_BYTES//1048576} MB limit for one scan.")
            return s
    return s


def ingest(folder: str | Path, client=None, progress=None) -> Scan:
    """Index everything supported under `folder`, in place."""
    s = preview(folder)
    if s.error or not s.files:
        if not s.error:
            s.error = "No supported documents found in that folder."
        return s

    t0 = time.perf_counter()
    paths = [Path(f) for f in s.files]
    for i, p in enumerate(paths, 1):
        if progress:
            progress(i, len(paths), p.name)
        try:
            stats = pipeline.build([p], client=client, verbose=False)
            if stats.get("chunks"):
                s.indexed += 1
                s.chunks += stats["chunks"]
        except pipeline.SelfGenerated:
            s.skipped_self += 1
        except Exception:
            s.failed += 1
    s.seconds = time.perf_counter() - t0
    return s



